def _category_for_ext(ext: str) -> str:
    e = (ext or "").lower()
    if e in IMAGE_EXTS:
        return "image"
    if e in ["mp3", "wav", "m4a", "flac", "ogg"]:
        return "audio"
    if e in ["mp4", "webm", "mov", "avi", "mkv"]:
        return "video"
    if e in ["pdf", "docx", "pptx", "txt", "md", "csv", "xlsx", "xls", "json", "log", "sql", "xml", "yaml", "ini", "py", "js", "sh"]:
        return "text"
    if e in ARCHIVE_EXTS:
        return "archive"
    return "other"


